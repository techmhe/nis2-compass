    keys = ("4h", "24h", "72h", "1w")
    return {
        dim: dict(zip(keys, vals, strict=True))
        for dim, vals in (
            ("operational", op),
            ("financial", fin),
            ("legal", leg),
            ("safety", saf),
            ("reputation", rep),
        )
    }


